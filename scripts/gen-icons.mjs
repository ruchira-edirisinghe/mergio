import { siTwitch, siYoutube, siKick, siTiktok, siFacebook } from 'simple-icons';
import { writeFileSync } from 'node:fs';
const brands = { twitch: siTwitch, youtube: siYoutube, kick: siKick, tiktok: siTiktok, facebook: siFacebook };
const out = Object.fromEntries(Object.entries(brands).map(([k, v]) => [k, { path: v.path, hex: '#' + v.hex, title: v.title }]));
writeFileSync(new URL('../public/shared/icons.js', import.meta.url),
  `/* Generated by scripts/gen-icons.mjs from Simple Icons (CC0 1.0). Do not edit by hand. */\nwindow.ZUNO_BRANDS = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote public/shared/icons.js');
