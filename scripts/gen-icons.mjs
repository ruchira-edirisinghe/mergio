// Generates public/shared/icons.js from Simple Icons (CC0). Run: npm run icons
import { siTwitch, siYoutube, siKick, siTiktok, siFacebook, siDiscord, siTelegram, siWhatsapp, siX } from 'simple-icons';
import { writeFileSync } from 'node:fs';
// the five platforms, then the apps a go-live alert can be sent or shared to
const brands = { twitch: siTwitch, youtube: siYoutube, kick: siKick, tiktok: siTiktok, facebook: siFacebook, discord: siDiscord, telegram: siTelegram, whatsapp: siWhatsapp, x: siX };
const out = Object.fromEntries(Object.entries(brands).map(([k, v]) => [k, { path: v.path, hex: '#' + v.hex, title: v.title }]));
writeFileSync(new URL('../public/shared/icons.js', import.meta.url),
  `/* Generated by scripts/gen-icons.mjs from Simple Icons (CC0 1.0). Do not edit by hand. */\nwindow.MERGIO_BRANDS = ${JSON.stringify(out, null, 2)};\n`);
console.log('wrote public/shared/icons.js');
